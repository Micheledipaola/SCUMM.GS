def byte_glifo(car):
    """The eight bytes of one character, leftmost pixel in bit seven."""
    righe = GLIFI.get(car, GLIFI['?']).split('/')
    out = []
    for r in righe[:8]:
        v = 0
        for i, c in enumerate(r[:5]):
            if c == '1':
                v |= 0x80 >> i
        out.append(v)
    while len(out) < 8:
        out.append(0)
    return out


