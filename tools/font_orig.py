"""font_orig.py - an original 8x8 font for the interpreter.

SCUMM V2 keeps no font in the .LFL files: on DOS it lives inside the
game's executable, so it is game data and cannot be distributed. This is
a font drawn from scratch for this project instead, so the interpreter
builds and runs without anything of Lucasfilm's in it.

The shapes are five pixels wide and seven tall inside the eight by eight
cell, which leaves one row under the letters and three columns after
them: at this size that is what keeps two capitals from touching. The
five that hang below the line - g j p q y - use the eighth row for the
tail.

Each glyph is written here as its rows, one string of ones and zeros per
row, top first. What the interpreter wants is one byte per row with the
leftmost pixel in bit seven, which is what emit() builds.

    python3 tools/font_orig.py > src/fontdata.s

To use the game's own font instead, see tools/font_mm.py. The file it
writes has the same name and shape, and the build picks up whichever one
is there.
"""
