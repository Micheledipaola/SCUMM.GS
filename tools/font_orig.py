    print("*")
    print("* One byte per row, eight rows per character, leftmost pixel in bit")
    print("* seven. A hundred and twenty-eight characters, so the table is a")
    print("* round kilobyte; everything below the space is blank.")
    print("FontData         anop")
    for c in range(128):
        car = chr(c)
        b = byte_glifo(car) if 32 <= c < 127 else [0] * 8
        nome = car if 33 <= c < 127 else f"${c:02X}"
        print("                 hex   " + ''.join(f"{x:02X}" for x in b)
              + f"   ; {nome}")


