USA_CRC = 0x0D9F5BD1


def load_prg(path):
    raw = open(path, 'rb').read()
    if raw[:4] == b'NES\x1a':
        prg = raw[16:16 + 262144]
    else:
        prg = raw[:262144]
    if len(prg) < 262144:
        raise SystemExit(f'PRG too short: {len(prg)}')
    crc = zlib.crc32(prg) & 0xFFFFFFFF
    if crc != USA_CRC:
        print(f'warning: PRG crc {crc:08X} expected {USA_CRC:08X} (USA)')
    else:
        print(f'USA PRG ok crc={crc:08X}')
    return prg


def classify(blob):
    if len(blob) < 2:
        return 'empty', 0, 0
    chan, typ = blob[0], blob[1]
    if chan == 2 and typ == 100:
        nnotes = blob[2] if len(blob) > 2 else 0
        return 'music', chan, nnotes
    if chan in (0, 1, 4) and typ == 10:
        return 'sfx', chan, typ
    return f'other c={chan} t={typ}', chan, typ


def scan_startsound(code):
    """V2 startSound is 0x1C + byte id (0x9C = from variable)."""
    hits = []
    i = 0
    while i < len(code) - 1:
        op = code[i]
        if op == 0x1C:
            hits.append(('const', code[i + 1], i))
            i += 2
            continue
        if op == 0x9C:
            hits.append(('var', code[i + 1], i))
            i += 2
            continue
        i += 1
    return hits


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else 'Maniac Mansion (USA).nes'
    prg = load_prg(path)
    dest = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        'build', 'nes_dump')
    os.makedirs(dest, exist_ok=True)

    print('\n=== sounds ===')
    calls = {i: [] for i in range(len(SOUNDS))}
    for i, (off, ln) in enumerate(SOUNDS):
        blob = prg[off:off + ln]
        kind, chan, extra = classify(blob)
        tag = ''
        if kind == 'music':
            tag = f'  notes={extra}'
        print(f'  {i:3d} ${off:05X} {ln:5d} B  {kind}{tag}')
        if kind == 'music':
            open(os.path.join(dest, f'snd{i:02d}.bin'), 'wb').write(blob)

    print('\n=== startSound in global scripts ===')
    for si, (off, ln) in enumerate(SCRIPTS):
        if ln < 4:
            continue
        blob = prg[off:off + ln]
        size = struct.unpack_from('<H', blob, 0)[0]
        code = blob[2:size] if size == ln else blob[2:]
        for kind, sid, at in scan_startsound(code):
            if kind == 'const' and sid < len(SOUNDS):
                calls[sid].append(si)
                skind, _, _ = classify(prg[SOUNDS[sid][0]:SOUNDS[sid][0] + SOUNDS[sid][1]])
                if skind == 'music' or sid >= 49:
                    print(f'  script {si:3d} +{at:04X}: startSound({sid})  [{skind}]')
            elif kind == 'var':
                print(f'  script {si:3d} +{at:04X}: startSound(var {sid})')

    print('\n=== music ids: who calls them ===')
    for i, (off, ln) in enumerate(SOUNDS):
        kind, _, n = classify(prg[off:off + ln])
        if kind != 'music':
            continue
        who = calls[i]
        print(f'  sound {i:3d}  {ln:5d} B  notes={n:3d}  scripts={who or "-"}')

    print(f'\ndumped music blobs to {dest}')


if __name__ == '__main__':
    main()
